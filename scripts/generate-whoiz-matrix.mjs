#!/usr/bin/env node
//
// Generates lib/whoiz-matrix.ts — a dot-grid representation of the WHOIZ logo.
//
// It rasterizes public/logos/logo1.svg (the WHOIZ app icon: orange rounded-square
// with a white "W" mark) using sharp (already present as a transitive dep of next),
// then samples the grid and classifies each cell as one of:
//   edge     — the rounded-square perimeter (brand orange outline)
//   glyph    — the white "W" strokes
//   interior — the orange fill of the rounded square (rendered as a faint grid)
//
// Usage: node scripts/generate-whoiz-matrix.mjs

import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const GRID = 30;
const ALPHA_THRESHOLD = 40;

const srcPath = path.join(__dirname, "..", "public", "logos", "logo1.svg");
const outPath = path.join(__dirname, "..", "lib", "whoiz-matrix.ts");

const input = fs.readFileSync(srcPath);

const { data, info } = await sharp(input, { density: 150 })
  .resize(GRID, GRID, { fit: "fill" })
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

const inIcon = (col, row) => {
  const alpha = data[(row * info.width + col) * 4 + 3];
  return alpha > ALPHA_THRESHOLD;
};

const isGlyph = (col, row) => {
  const idx = (row * info.width + col) * 4;
  const [r, g, b] = [data[idx], data[idx + 1], data[idx + 2]];
  return r > 210 && g > 210 && b > 210;
};

const neighbors = [
  [1, 0],
  [-1, 0],
  [0, 1],
  [0, -1],
];

const edge = [];
const glyph = [];
const interior = [];

for (let row = 0; row < info.height; row++) {
  for (let col = 0; col < info.width; col++) {
    if (!inIcon(col, row)) continue;
    if (isGlyph(col, row)) {
      glyph.push([col, row]);
      continue;
    }
    const onPerimeter = neighbors.some(([dx, dy]) => !inIcon(col + dx, row + dy));
    if (onPerimeter) edge.push([col, row]);
    else interior.push([col, row]);
  }
}

const content = `// Generated by scripts/generate-whoiz-matrix.mjs — do not edit by hand.
// Rasterized from public/logos/logo1.svg (WHOIZ app icon: orange rounded square + white "W").
//   edge     — rounded-square perimeter (orange outline)
//   glyph    — the "W" strokes (brand accent, emphasized)
//   interior — rounded-square fill (rendered as a faint grid)
export const WHOIZ_MATRIX = {
  cols: ${info.width},
  rows: ${info.height},
  edge: ${JSON.stringify(edge)},
  glyph: ${JSON.stringify(glyph)},
  interior: ${JSON.stringify(interior)},
} as const;
`;

fs.writeFileSync(outPath, content);

console.log(`Wrote edge:${edge.length} glyph:${glyph.length} interior:${interior.length} (${info.width}x${info.height}) to lib/whoiz-matrix.ts`);

const byKey = (arr) => new Set(arr.map(([x, y]) => `${x},${y}`));
const e = byKey(edge);
const g = byKey(glyph);
const i = byKey(interior);
console.log("Preview:  P=edge  W=glyph  .=interior");
for (let row = 0; row < info.height; row++) {
  let line = "";
  for (let col = 0; col < info.width; col++) {
    const key = `${col},${row}`;
    if (g.has(key)) line += "W";
    else if (e.has(key)) line += "P";
    else if (i.has(key)) line += ".";
    else line += " ";
  }
  console.log(line);
}